"""Deliverable 7: reproducible walkthrough evidence, written to docs/DEMO_OUTPUT.md.

Runs against a throwaway database (never data/tracker.db) and demonstrates:
two fictional reports, validation errors, a status transition through the HITL
gate, a 4-stage RAG query with per-stage results, the control plane
(guardrail, router, auto-repair, circuit breaker, ReAct trace), and audit records
with hash-chain verification.

    python scripts/demo_run.py                 # auto mode (real models if downloaded)
    python scripts/demo_run.py --mode fallback
    python scripts/demo_run.py --out somewhere.md
"""
from __future__ import annotations

import argparse
import json
import sqlite3
import sys
import tempfile
from datetime import timedelta
from pathlib import Path
from typing import Any, List, Optional, Sequence

ROOT = Path(__file__).resolve().parents[1]
for extra in (ROOT / "src", ROOT / "scripts"):
    if str(extra) not in sys.path:
        sys.path.insert(0, str(extra))

from pharma_intake import config  # noqa: E402
from pharma_intake.agent.assistant import Assistant  # noqa: E402
from pharma_intake.errors import ApprovalError, ApprovalPending, IntakeValidationError, InvalidTransition  # noqa: E402
from pharma_intake.rag.pipeline import build_pipeline  # noqa: E402
from pharma_intake.repository import Repository  # noqa: E402
from pharma_intake.workflow import WorkflowService  # noqa: E402
from seed import seed  # noqa: E402

DEFAULT_OUT = ROOT.parent / "docs" / "DEMO_OUTPUT.md"
EDIT_LOG = ROOT.parent / "logs" / "edit_audit.log"


def table(headers: Sequence[str], rows: Sequence[Sequence[Any]]) -> str:
    def cell(value: Any) -> str:
        return str(value).replace("|", "\\|").replace("\n", " ")

    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


class Doc:
    def __init__(self) -> None:
        self.parts: List[str] = []

    def h(self, level: int, text: str) -> None:
        self.parts.append(f"\n{'#' * level} {text}\n")

    def p(self, text: str) -> None:
        self.parts.append(text + "\n")

    def code(self, text: str, lang: str = "") -> None:
        self.parts.append(f"```{lang}\n{text}\n```\n")

    def render(self) -> str:
        return "\n".join(self.parts).strip() + "\n"


def run(mode: Optional[str] = None, out: Path = DEFAULT_OUT) -> str:
    tmp = Path(tempfile.mkdtemp(prefix="pharma_demo_"))
    repo = Repository(tmp / "demo.db")
    workflow = WorkflowService(repo)
    seeded = seed(repo, workflow)
    pipeline = build_pipeline(repo.list_reports(), mode=mode)
    assistant = Assistant(repo, workflow, pipeline, "OP-002")
    today = repo.today()
    doc = Doc()

    doc.p("# Demo output — walkthrough evidence (Deliverable 7)")
    doc.p(f"> Generated by `scripts/demo_run.py` on {today.isoformat()} against a throwaway database. "
          "All products, lots and narratives are **fictional**.")
    doc.p(table(["Component", "Active implementation"], [[k, f"`{v}`"] for k, v in pipeline.mode.items()]))

    doc.h(2, "0. Setup — fictional history for the knowledge base")
    doc.p(f"Seeded {len(seeded)} historical reports ({seeded[0]} … {seeded[-1]}) through the real API. "
          f"Status counts: `{repo.status_counts()}`. Knowledge corpus: {len(pipeline.chunks)} chunks "
          f"(5 SOPs + past reports).")

    # ------------------------------------------------------------ 1. two fictional reports
    doc.h(2, "1. Two fictional reports")
    doc.h(3, "1a. Mandatory-field validation (context-sensitive errors)")
    ref_a = repo.reserve_reference("OP-001")
    doc.p(f"Operator `OP-001` starts a report → reference **{ref_a}** is reserved on initiation. "
          "A first, incomplete Suspected Adverse Event submission is rejected:")
    try:
        repo.submit_report(ref_a, {"report_type": "Suspected Adverse Event", "product_name": "Velmiradine 2% cream",
                                   "batch_lot_number": "LOT-6409", "description": "Redness"}, "OP-001")
    except IntakeValidationError as exc:
        doc.p(table(["Field", "Message"], [[i.field, i.message] for i in exc.issues]))

    doc.h(3, "1b. Report A — Suspected Adverse Event (UI path)")
    data_a = {
        "report_type": "Suspected Adverse Event", "product_name": "Velmiradine 2% cream",
        "batch_lot_number": "LOT-64090", "date_received": (today - timedelta(days=1)).isoformat(),
        "reporter_type": "Consumer", "intake_channel": "Email",
        "description": "Consumer reported redness and itching at the application site after the second use.",
        "event_description": "Application site erythema and pruritus, described as mild by the reporter.",
        "event_onset_date": (today - timedelta(days=2)).isoformat(),
    }
    report_a = repo.submit_report(ref_a, data_a, "OP-001")
    doc.p(f"Saved **{report_a.ref_id}** · {report_a.report_type.value} · {report_a.product_name} · "
          f"{report_a.batch_lot_number} · status **{report_a.status.value}**.")

    doc.h(3, "1c. Report B — Product Quality Complaint (agent chat path, with auto-repair)")
    msg_b = ("Submit a new report: type=pqc; product=Ophtiralin 0.5% eye drops; lot=lot 12977; "
             f"received={(today - timedelta(days=1)).strftime('%Y/%m/%d')}; reporter=pharmacist; channel=phone; "
             "description=Pharmacist found a cracked dropper bottle inside a sealed carton; sample available.")
    doc.code(msg_b)
    reply_b = assistant.handle(msg_b)
    ref_b = reply_b.tool_results[0].data["ref_id"]
    doc.p(f"Route: **{reply_b.route.value}** → {reply_b.text}")
    doc.p("Auto-repairs applied before Pydantic validation:\n\n" +
          "\n".join(f"- {r}" for r in reply_b.tool_results[0].repairs))

    # ------------------------------------------------------------ 2. status transition + HITL
    doc.h(2, "2. Status transition through the Human-in-the-Loop gate")
    rows = []
    rows.append(["OP-001: New → In Review", workflow.advance(ref_a, "In Review", "OP-001").message])
    rows.append(["OP-001: In Review → Closed", workflow.advance(ref_a, "Closed", "OP-001").message])
    try:
        workflow.advance(ref_a, "Closed", "OP-003")
    except ApprovalPending as exc:
        rows.append(["OP-003 tries another transition while frozen", f"Refused: {exc}"])
    try:
        workflow.approve_closure(ref_a, "OP-001", attestation=True)
    except ApprovalError as exc:
        rows.append(["OP-001 (operator) tries to approve", f"Refused: {exc}"])
    try:
        workflow.approve_closure(ref_a, "REV-01", attestation=False)
    except ApprovalError as exc:
        rows.append(["REV-01 approves without attestation", f"Refused: {exc}"])
    rows.append(["REV-01 approves with attestation", workflow.approve_closure(ref_a, "REV-01", attestation=True).message])
    try:
        workflow.advance(ref_b, "Closed", "OP-002")
    except InvalidTransition as exc:
        rows.append([f"OP-002: {ref_b} New → Closed (skip)", f"Refused: {exc}"])
    doc.p(table(["Action", "Result"], rows))
    doc.p(f"Status history of {ref_a}:\n\n" + table(
        ["From", "To", "At (UTC)", "By"],
        [[h["from_status"] or "—", h["to_status"], h["changed_at"], h["changed_by"]] for h in repo.status_history(ref_a)]))

    # ------------------------------------------------------------ 3. multi-stage RAG
    doc.h(2, "3. Multi-stage hybrid RAG query")
    pipeline.index(repo.list_reports())
    query = "Have there been any reports of difficulty breathing?"
    rag = pipeline.answer(query)
    r = rag.retrieval
    doc.p(f"**Query:** `{query}` — the corpus never uses the phrase \"difficulty breathing\"; "
          "past reports use the clinical term *dyspnea*.")
    doc.p(table(["Stage", "Setting", "Candidates", "Top 5 (chunk · score)"], [
        ["1 BM25", f"k1={config.BM25_K1}, b={config.BM25_B}, top-{config.BM25_TOP_K}", len(r.bm25),
         ", ".join(f"{h.chunk_id} · {h.score:.2f}" for h in r.bm25[:5])],
        ["2 Bi-encoder", "cosine, 512/64 chunks, top-50", len(r.dense),
         ", ".join(f"{h.chunk_id} · {h.score:.3f}" for h in r.dense[:5])],
        ["3 RRF", f"k={config.RRF_K}", len(r.fused),
         ", ".join(f"{h.chunk_id} · {h.score:.4f} ({h.detail})" for h in r.fused[:5])],
        ["4 Cross-encoder", f"threshold {config.RERANK_THRESHOLD}, top ≤ {config.RERANK_TOP_K}", len(r.reranked),
         ", ".join(f"{h.chunk_id} · {h.score:.3f} {h.detail}" for h in r.reranked[:5])],
    ]))
    doc.p("**Answer (extractive, grounded):**")
    doc.code(rag.answer.text + ("\n\nSources: " + "; ".join(rag.answer.citations) if rag.answer.citations else ""))
    for q in ("Which complaints involve LOT-88392?", "Who can approve closing a report?", "What is the capital of France?"):
        extra = pipeline.retrieve(q)
        doc.p(f"- `{q}` → kept {len(extra.final)}: " +
              (", ".join(f"{c.chunk_id} ({s:.2f})" for c, s in zip(extra.final, extra.final_scores)) or
               "none — answer is \"No sufficiently relevant record found\" (no hallucination)"))
    doc.p("<details><summary>Grounded generation prompt</summary>\n")
    doc.code(rag.prompt, "markdown")
    doc.p("</details>")

    # ------------------------------------------------------------ 4. control plane
    doc.h(2, "4. Agentic control plane")
    rows = []
    for message in ("hello", "What does SOP-004 say about closure approval?",
                    "I want to submit a new adverse event report", f"status of {ref_b}"):
        decision = assistant.router.route(message)
        rows.append([message, decision.route.value, f"{decision.tier}: {decision.rule}"])
    doc.p("**Deterministic router (step 3):**\n\n" + table(["Message", "Route", "Tier: rule"], rows))
    blocked = assistant.handle("Did Velmiradine cause the erythema? Should it be reported to the regulator?")
    doc.p(f"**Input guardrail (step 5):** reason `{blocked.guardrail_reason}` → {blocked.text}")
    _, year, seq = ref_b.split("-")
    sloppy = f"move ref {year}-{int(seq)} to in-review"
    repaired = assistant.handle(sloppy)
    doc.p(f"**Type-safe tool + auto-repair (step 1):** `{sloppy}` → {repaired.text} Repairs: "
          f"`{'; '.join(repaired.tool_results[0].repairs)}`")
    bad = f"move REF-{year}-9999 to in review"
    doc.p(f"**Circuit breaker (step 5):** the same invalid call `{bad}` sent three times:")
    rows = []
    for attempt in range(1, 4):
        reply = assistant.handle(bad)
        res = reply.tool_results[0]
        rows.append([attempt, res.error.code if res.error else "ok", res.attempts, "OPEN — halted" if reply.halted else "closed"])
    after = assistant.handle("Who can approve closing a report?")
    rows.append(["4 (a valid RAG query)", "circuit_open", "—", "refused: " + after.text[:60] + "…"])
    doc.p(table(["Attempt", "Result", "Consecutive identical invalid", "Breaker"], rows))
    assistant.reset()
    doc.p("A human then resets the agent (`CIRCUIT_BREAKER_RESET` is audited).")
    doc.p("**Dual memory (step 2) — ReAct trace of the auto-repair turn (short-term, volatile):**")
    doc.p(table(["#", "Kind", "Content"],
                [[s.step, s.kind, s.content] for s in assistant.memory.steps(repaired.turn)]))

    # ------------------------------------------------------------ 5. audit
    doc.h(2, "5. Audit records (long-term memory)")
    for ref in (ref_a, ref_b):
        doc.p(f"**{ref}**\n\n" + table(["#", "UTC", "Actor", "Action", "Details"], [
            [e.id, e.ts, e.actor, e.action, json.dumps(e.details, sort_keys=True)] for e in repo.audit_entries(ref_id=ref)]))
    control = [e for e in repo.audit_entries() if e.action in
               {"GUARDRAIL_BLOCKED", "CIRCUIT_BREAKER_TRIPPED", "CIRCUIT_BREAKER_RESET", "RAG_QUERY"}][-5:]
    doc.p("Control-plane events (queries stored only as hash + length):\n\n" + table(
        ["#", "Actor", "Action", "Details"], [[e.id, e.actor, e.action, json.dumps(e.details, sort_keys=True)] for e in control]))
    chain = repo.verify_audit_chain()
    doc.p(f"**Hash-chain verification:** ok={chain.ok}, entries checked={chain.checked}.")
    conn = sqlite3.connect(repo.path)
    try:
        conn.execute("UPDATE audit_log SET actor = 'OP-003' WHERE id = 1")
        tamper = "NOT BLOCKED"
    except sqlite3.IntegrityError as exc:
        tamper = f"blocked by trigger: `{exc}`"
    finally:
        conn.close()
    doc.p(f"**Tamper attempt** (`UPDATE audit_log …`): {tamper}.")

    # ------------------------------------------------------------ 6. governance hook
    doc.h(2, "6. Governance hook evidence")
    if EDIT_LOG.exists():
        lines = [l for l in EDIT_LOG.read_text(encoding="utf-8").splitlines() if l.strip()]
        doc.p(f"`logs/edit_audit.log` holds **{len(lines)}** content-free edit events written by the PostToolUse hook "
              "during development. Last three:")
        doc.code("\n".join(lines[-3:]), "json")
    else:
        doc.p("`logs/edit_audit.log` not found.")

    text = doc.render()
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate docs/DEMO_OUTPUT.md")
    parser.add_argument("--mode", choices=["auto", "real", "fallback"], default=None)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    text = run(args.mode, args.out)
    print(text)
    print(f"\nWritten to {args.out.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
